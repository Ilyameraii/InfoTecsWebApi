using Entities;

namespace Services.Contracts;

/// <summary>
/// Предоставляет функциональность расчёта интегральных (агрегированных) показателей
/// по набору значений, полученных из CSV-файла, в соответствии с бизнес-требованиями
/// к таблице Results (дельта времени, среднее, медиана, минимум, максимум и т.д.).
/// </summary>
public interface ICsvAggregator
{
    /// <summary>
    /// Вычисляет агрегированные показатели по коллекции распарсенных строк CSV-файла.
    /// </summary>
    /// <param name="fileName">Имя обрабатываемого файла, которое будет присвоено результату.</param>
    /// <param name="rows">Коллекция строк CSV-файла, прошедших валидацию, по которым выполняется расчёт.</param>
    /// <returns>
    /// Объект <see cref="ResultRecord"/>, содержащий рассчитанные интегральные показатели:
    /// дельту времени между минимальной и максимальной датой, минимальную дату,
    /// среднее время выполнения, среднее, медианное, максимальное и минимальное значения показателя.
    /// </returns>
    ResultRecord Calculate(string fileName, IReadOnlyCollection<ValueRecord> rows);
}